        /// <summary>Returns the band containing the frequency (MHz), or null.</summary>
        public static string? FindBand(double frequencyMHz)
        {
            return Bands.FirstOrDefault(b => frequencyMHz >= b.Min && frequencyMHz <= b.Max)?.Band;
        }

        /// <summary>Parses a frequency in MHz written with '.' or ',' as decimal separator, regardless of the PC's culture.</summary>
        public static bool TryParseMHz(string text, out double mhz)
        {
            return double.TryParse((text ?? string.Empty).Trim().Replace(',', '.'),
                NumberStyles.Float, CultureInfo.InvariantCulture, out mhz);
        }

        /// <summary>True when the mode is one of <see cref="Modes"/> (case-insensitive).</summary>
        public static bool IsValidMode(string mode)
        {
            return Modes.Any(m => string.Equals(m, mode, StringComparison.OrdinalIgnoreCase));
        }

        /// <summary>DXCC entities whose name contains the text (case-insensitive).</summary>
        public static IReadOnlyList<KeyValuePair<int, string>> SearchDxcc(string text)
        {
            string upper = (text ?? string.Empty).Trim().ToUpperInvariant();
            return Dxcc.Where(x => x.Value.Contains(upper, StringComparison.Ordinal)).ToList();
        }

        /// <summary>DXCC entity number for an exact country name, or empty string.</summary>
        public static string GetDxccByCountry(string country)
        {
            string upper = (country ?? string.Empty).Trim().ToUpperInvariant();
            int number = Dxcc.FirstOrDefault(x => x.Value == upper).Key;
            return number > 0 ? number.ToString(CultureInfo.InvariantCulture) : string.Empty;
        }
